# Draws the TGeshka logo (lavender circle, white paper plane, the same as in
# TGeshka Desktop: Telegram/build/tgeshka/gen_icons.py) and writes the Android
# launcher icons into TMessagesProj/src/main/res:
#   - adaptive icon layers as vector drawables (tgeshka_icon_*.xml),
#   - legacy PNG icons for Android 6/7 (mipmap-*/ic_launcher*.png).
# Run: python Tools/tgeshka/gen_icons.py   (requires Pillow)

import os

from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.normpath(os.path.join(HERE, '..', '..', 'TMessagesProj', 'src', 'main', 'res'))

TOP = (188, 170, 247)
BOTTOM = (132, 112, 222)
PLANE = (255, 255, 255)
FOLD = (230, 223, 255)

# Plane in a 100x100 box, circle is centered at (50, 50) with radius 50.
BODY = [(16, 48), (80, 22), (68, 78), (50, 66), (40, 76), (39, 59)]
FOLD_PART = [(39, 59), (73, 30), (50, 66), (40, 76)]

LEGACY = {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}
SUPERSAMPLE = 8


def lerp(a, b, t):
    return tuple(int(round(x + (y - x) * t)) for x, y in zip(a, b))


def hex_color(color):
    return '#FF%02X%02X%02X' % color


def draw_logo(size, margin):
    big = size * SUPERSAMPLE
    image = Image.new('RGBA', (big, big), (0, 0, 0, 0))
    inner = big - 2 * int(round(margin * big))
    offset = (big - inner) // 2

    steps = 256
    gradient = Image.new('RGBA', (steps, steps))
    pixels = gradient.load()
    for y in range(steps):
        for x in range(steps):
            t = (x + y) / (2.0 * (steps - 1))
            pixels[x, y] = lerp(TOP, BOTTOM, t) + (255,)
    gradient = gradient.resize((inner, inner), Image.BICUBIC)
    mask = Image.new('L', (inner, inner), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, inner - 1, inner - 1), fill=255)
    image.paste(gradient, (offset, offset), mask)

    draw = ImageDraw.Draw(image)

    def scale(points):
        return [(offset + x * inner / 100.0, offset + y * inner / 100.0) for x, y in points]

    draw.polygon(scale(BODY), fill=PLANE + (255,))
    draw.polygon(scale(FOLD_PART), fill=FOLD + (255,))
    return image.resize((size, size), Image.LANCZOS)


def adaptive_path(points):
    # 108dp canvas, the plane is scaled into the 66dp safe zone around (54, 54).
    s = 0.62
    mapped = [(54 + (x - 48) * s, 54 + (y - 50) * s) for x, y in points]
    return 'M' + ' L'.join('%.2f,%.2f' % p for p in mapped) + ' Z'


def write(path, text):
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def main():
    write(os.path.join(RES, 'drawable', 'tgeshka_icon_background.xml'), '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by Tools/tgeshka/gen_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="0"
                android:startY="0"
                android:endX="108"
                android:endY="108"
                android:startColor="%s"
                android:endColor="%s" />
        </aapt:attr>
    </path>
</vector>
''' % (hex_color(TOP), hex_color(BOTTOM)))

    write(os.path.join(RES, 'drawable', 'tgeshka_icon_foreground.xml'), '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by Tools/tgeshka/gen_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="%s" android:pathData="%s" />
    <path android:fillColor="%s" android:pathData="%s" />
</vector>
''' % (hex_color(PLANE), adaptive_path(BODY), hex_color(FOLD), adaptive_path(FOLD_PART)))

    write(os.path.join(RES, 'drawable', 'tgeshka_icon_monochrome.xml'), '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by Tools/tgeshka/gen_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="#FFFFFFFF" android:pathData="%s" />
</vector>
''' % adaptive_path(BODY))

    adaptive = '''<?xml version="1.0" encoding="utf-8"?>
<!-- TGeshka launcher icon, layers from Tools/tgeshka/gen_icons.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/tgeshka_icon_background" />
    <foreground android:drawable="@drawable/tgeshka_icon_foreground" />
    <monochrome android:drawable="@drawable/tgeshka_icon_monochrome" />
</adaptive-icon>
'''
    for name in ('ic_launcher.xml', 'ic_launcher_round.xml'):
        write(os.path.join(RES, 'mipmap-anydpi-v26', name), adaptive)

    for density, size in LEGACY.items():
        folder = os.path.join(RES, 'mipmap-' + density)
        logo = draw_logo(size, 4.0 / 48.0)
        logo.save(os.path.join(folder, 'ic_launcher.png'))
        logo.save(os.path.join(folder, 'ic_launcher_round.png'))

    print('Icons written to ' + RES)


if __name__ == '__main__':
    main()
